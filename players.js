function wobble(name, i) {
  let h = 2166136261;
  for (const ch of `${name}#${i}`) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619); }
  return ((h >>> 0) % 7) - 3;
}
function expandRoster(rows) {
  return rows.map(([era, name, cc, years, style, tier, slams, college]) => {
    const base = TIER_BASE[tier], shape = STYLE_SHAPE[style] || STYLE_SHAPE["All-court"];
    const ratings = base.map((b, i) => Math.max(40, Math.min(99, b + shape[i] + wobble(name, i))));
    return [era, name, cc, years, style, slams, college, ...ratings];
  });
}
